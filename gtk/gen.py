#!/usr/bin/env python3
"""Generated pieces of the GTK binding's build, so adding a widget or a gallery section is adding
its files, with no shared list to edit.

    gen.py list src|headers|sections|tests     files meson compiles (relative to gtk/)
    gen.py umbrella OUT HEADER...              omarchy-gtk.h including every public header
    gen.py types OUT HEADER...                 omarchy_ensure_types(): every OMARCHY_TYPE_*
    gen.py sections OUT FILE...                the gallery's section table, in spec order
"""

import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
# spec/gallery.md's order (qt/gallery/Sections.qml).
ORDER = ["buttons", "toggles", "inputs", "slider", "surfaces", "lists", "tiles", "progress", "messages", "menus",
         "navigation", "forms", "pickers", "data", "layout", "timeline", "color", "composed", "tokens"]
PRIVATE = {"omarchy-private.h", "omarchy-tokens.h", "omarchy-gtk.h"}


def public_headers():
    return sorted(p for p in (HERE / "src").glob("omarchy-*.h") if p.name not in PRIVATE and not p.name.endswith("-private.h"))


def main():
    cmd = sys.argv[1]
    if cmd == "list":
        what = sys.argv[2]
        if what == "src":
            files = sorted((HERE / "src").glob("*.c"))
        elif what == "headers":
            files = public_headers()
        elif what == "sections":
            files = sorted((HERE / "gallery/sections").glob("*.c"))
        elif what == "tests":
            files = sorted((HERE / "tests").glob("test-*.c"))
        else:
            sys.exit(f"unknown list {what}")
        print("\n".join(str(f.relative_to(HERE)) for f in files))
    elif cmd == "umbrella":
        out, headers = sys.argv[2], sys.argv[3:]
        lines = ["/* omarchy-gtk.h: Omarchy UI for GTK 4. Generated by gen.py from src/omarchy-*.h. */",
                 "#pragma once", "", "#define OMARCHY_GTK_INSIDE", "#include <gtk/gtk.h>", "",
                 '#include "omarchy-version.h"']
        lines += [f'#include "{Path(h).name}"' for h in sorted(headers, key=lambda h: Path(h).name)]
        lines += ["", "G_BEGIN_DECLS", "OmarchyTheme *omarchy_gtk_init (void);", "OmarchyTheme *omarchy_init (void);", "const char *omarchy_get_version (void);",
                  "void omarchy_ensure_types (void);", "G_END_DECLS", "#undef OMARCHY_GTK_INSIDE", ""]
        Path(out).write_text("\n".join(lines))
    elif cmd == "types":
        out, headers = sys.argv[2], sys.argv[3:]
        types = []
        for h in sorted(headers):
            types += re.findall(r"#define\s+(OMARCHY_TYPE_\w+)\s", Path(h).read_text())
        body = "\n".join(f"  g_type_ensure ({t});" for t in sorted(set(types)))
        Path(out).write_text(
            '/* Generated by gen.py. */\n#include "omarchy-gtk.h"\n\n'
            "/**\n * omarchy_ensure_types:\n *\n * Registers every kit widget type, so GtkBuilder files can name them.\n */\n"
            f"void\nomarchy_ensure_types (void)\n{{\n{body}\n}}\n")
    elif cmd == "sections":
        out, files = sys.argv[2], sys.argv[3:]
        names = {Path(f).stem for f in files}
        have = [n for n in ORDER if n in names] + sorted(n for n in names if n not in ORDER)
        decls = "\n".join(f"GtkWidget *gallery_section_{n} (void);" for n in have)
        rows = "\n".join(f'  {{ "{n}", gallery_section_{n} }},' for n in have)
        Path(out).write_text(f'/* Generated by gen.py. */\n#include "gallery.h"\n\n{decls}\n\n'
                             f"const GallerySection gallery_sections[] = {{\n{rows}\n  {{ NULL, NULL }},\n}};\n")
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
