#!/usr/bin/env python3
"""Write omarchy-gtk/src/widgets.rs from gtk/src/omarchy-*.h: a glib::wrapper! per kit type
(G_DECLARE_FINAL_TYPE), so the Rust crate binds every widget the C library has without a second
implementation. Run after adding a widget: python3 gtk/rust/gen-widgets.py"""
import re
from pathlib import Path

here = Path(__file__).resolve().parent
src = here.parent / "src"
types = []
for h in sorted(src.glob("omarchy-*.h")):
    for m in re.finditer(r"G_DECLARE_FINAL_TYPE \((Omarchy(\w+)), (omarchy_\w+), OMARCHY, \w+, (\w+)\)", h.read_text()):
        c, name, prefix, parent = m.groups()
        types.append((c, name, prefix, parent))
out = ["// Generated by gtk/rust/gen-widgets.py from gtk/src/omarchy-*.h. Don't edit.",
       "#![allow(clippy::all)]", "use crate::ffi;", ""]
decls = []
for c, name, prefix, parent in types:
    decls.append(f"    #[repr(C)] pub struct {c} {{ _p: [u8; 0] }}\n    #[repr(C)] pub struct {c}Class {{ _p: [u8; 0] }}\n    pub fn {prefix}_get_type() -> glib::ffi::GType;")
    if parent == "GtkWidget":
        ext = "@extends gtk::Widget, @implements gtk::Accessible, gtk::Buildable, gtk::ConstraintTarget"
    else:
        ext = ""
    out.append(f"glib::wrapper! {{\n    /// `{c}` (see the C library's gtk-doc and spec/components.md).\n"
               f"    pub struct {name}(Object<ffi::{c}, ffi::{c}Class>) {ext};\n"
               f"    match fn {{ type_ => || ffi::{prefix}_get_type(), }}\n}}\n")
(here / "omarchy-gtk/src/widgets.rs").write_text("\n".join(out))
ffi = ["// Generated by gtk/rust/gen-widgets.py. Don't edit.", "#![allow(non_camel_case_types, dead_code)]",
       "use std::os::raw::c_char;", "pub use crate::ffi_manual::*;", "", "unsafe extern \"C\" {"]
structs = []
fns = []
for c, name, prefix, parent in types:
    structs.append(f"#[repr(C)] pub struct {c} {{ _p: [u8; 0] }}\n#[repr(C)] pub struct {c}Class {{ _p: [u8; 0] }}")
    fns.append(f"    pub fn {prefix}_get_type() -> glib::ffi::GType;")
(here / "omarchy-gtk/src/ffi.rs").write_text("\n".join(["// Generated by gtk/rust/gen-widgets.py. Don't edit.",
    "#![allow(non_camel_case_types, dead_code)]", "pub use crate::ffi_manual::*;", ""] + structs + ["", "unsafe extern \"C\" {"] + fns + ["}", ""]))
print(f"{len(types)} types")
