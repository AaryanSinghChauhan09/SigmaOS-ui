#!/usr/bin/env node
// Write src/elements/index.d.ts from the elements' sources: one class per element with its
// properties (from `static props`), and the tag map, so TypeScript knows
// document.querySelector("omarchy-button").selected. web/build runs it; --check fails when stale.

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const dir = join(dirname(fileURLToPath(import.meta.url)), "../src/elements");
const TS = { bool: "boolean", string: "string", number: "number", json: "any" };
const classes = new Map(); // name -> { base, props: [[name, type]] }
const tags = []; // [tag, class]

for (const f of readdirSync(dir).filter((f) => f.endsWith(".js")).sort()) {
  const src = readFileSync(join(dir, f), "utf8");
  for (const m of src.matchAll(/export class (\w+) extends (\w+) \{([\s\S]*?)(?=\n(?:export|\/\/ -{5}|$))/g)) {
    const [, name, base, body] = m;
    const props = [];
    const p = /static props = \{([\s\S]*?)\};/.exec(body);
    if (p) {
      for (const e of p[1].matchAll(/(\w+):\s*\[\s*"(\w+)"/g)) props.push([e[1], TS[e[2]] || "any"]);
    }
    const methods = [...body.matchAll(/^  (?!static|constructor|setup|update|get |set |_)(\w+)\(([^)]*)\)\s*\{/gm)].map((x) => [x[1], x[2]]);
    classes.set(name, { base, props, methods });
  }
  const el = /export const elements = \{([\s\S]*?)\};/.exec(src);
  if (el) for (const e of el[1].matchAll(/"(omarchy-[\w-]+)":\s*(\w+)/g)) tags.push([e[1], e[2]]);
}

const lines = [
  "// Generated by web/tools/gen-types.mjs from the elements' sources. Don't edit.",
  "",
  "/** The base of every element: properties mirror their kebab-case attributes. */",
  "export class OmarchyElement extends HTMLElement {",
  "  /** One of the kit's strings in the display language. */",
  "  t(key: string, fallback?: string, ...args: unknown[]): string;",
  "}",
  "",
];
for (const [name, c] of classes) {
  if (name === "OmarchyElement") continue;
  const base = c.base === "HTMLElement" || c.base === "EventTarget" || classes.has(c.base) ? c.base : "OmarchyElement";
  lines.push(`export class ${name} extends ${base} {`);
  for (const [p, t] of c.props) lines.push(`  ${p}: ${t};`);
  for (const [m, args] of c.methods) {
    const params = args.split(",").map((a) => a.trim()).filter(Boolean).map((a) => `${a.split("=")[0].trim().replace(/[{}]/g, "") || "arg"}?: any`);
    lines.push(`  ${m}(${params.join(", ")}): any;`);
  }
  lines.push("}");
}
lines.push("", "/** Define every <omarchy-*> element (importing @omarchy/ui does it). */", "export function defineElements(): void;");
lines.push("/** Every element's tag and class. */", "export function elementTags(): Record<string, typeof HTMLElement>;", "");
lines.push("declare global {", "  interface HTMLElementTagNameMap {");
for (const [tag, cls] of tags) lines.push(`    "${tag}": ${cls};`);
lines.push("  }", "}", "");

const out = lines.join("\n");
const path = join(dir, "index.d.ts");
if (process.argv.includes("--check")) {
  let cur = "";
  try {
    cur = readFileSync(path, "utf8");
  } catch {}
  if (cur !== out) {
    console.error("src/elements/index.d.ts is stale (node web/tools/gen-types.mjs)");
    process.exit(1);
  }
} else {
  writeFileSync(path, out);
  console.log(`types: ${tags.length} elements`);
}
